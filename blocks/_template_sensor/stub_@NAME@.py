#!/usr/bin/env python3
"""stub_@NAME@.py - the @NAME@ world-driven sensor (SL-0030 template).

Generated by `./sim new --sensor @NAME@`. The contract beside this file
(sensor.yaml) declares the surface: what world truth it reads, the
model params (world.sensors.@NAME@ overrides them) and the output seam.
Replace tick() with the real model; keep the seed/rate/noise plumbing.

This reference model reports the truth entities in range once per
model `rate_hz` tick: the reported position is the truth plus a seeded
gaussian offset of `noise_m` sigma, dropped with probability `p_drop`,
and fires `@NAME@.range` on the capability namespace. Detection rows
land in truth.jsonl for the sensor_error assert.

Config (injected by the world loader, like every stub):
    stub: {world, seed, unit, pose_port}
"""

import os
import sys

# bytecode under var/pycache from the first import on (simlib sets it
# too, but only after itself is compiled - that left __pycache__ dirs)
sys.pycache_prefix = os.environ.setdefault(
    "PYTHONPYCACHEPREFIX",
    os.path.join(os.environ.get("SIM_VAR_DIR") or os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__)))), "var"), "pycache"))

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))       # blocks/<name>/ -> repo root
sys.path.insert(0, os.path.join(ROOT, "stubs"))
sys.path.insert(0, os.path.join(ROOT, "engine"))
from stub_base import StubBase        # noqa: E402
import geo_projection as gp           # noqa: E402

NS = "@NAME@"

ADVERT = {
    "schema": "de.cap/1",
    "ns": NS,
    "module": "stub_@NAME@",
    "ver": "0.1.0",
    "actions": {},
    "events": {
        "range": {
            "desc": "Nearest entity in range, every model tick",
            "payload": {
                "tid": {"type": "string"},
                "range_m": {"type": "number", "unit": "m"},
                "pos": {"type": "geo"},
            },
        },
    },
    "state": {"seen": {"type": "int"}},
}


class StubSensor(StubBase):
    MODULE_CLASS = "gen"
    MODULE_VERSION = "0.1.0"

    def __init__(self, argv):
        super().__init__(argv, "stub_@NAME@")
        m = self.sensor_params()       # contract.model + world overrides
        self.rate_hz = float(m.get("rate_hz", 2.0))
        self.range_m = float(m.get("range_m", 150.0))
        self.noise_m = float(m.get("noise_m", 1.5))
        self.p_drop = float(m.get("p_drop", 0.0))
        self._tick_i = -1
        self._seen = 0

    def reset_run(self):
        self._tick_i = -1
        self._seen = 0

    # ----------------------------------------------------- databus out

    def event(self, payload):
        self.log.log("EVENT", {"d": f"{NS}.range", "ed": payload},
                     ms=self.clock_ms())
        if self.facade is not None:
            self.facade.fire_event(NS, "range", payload)

    def state(self, changed, full=False):
        self.log.log("STATE", changed, ms=self.clock_ms())
        if self.facade is not None:
            self.facade.publish_state(NS, changed, full)

    # ------------------------------------------------------------- model

    def tick(self, t_s, _frame20):
        if self.world is None or self.rate_hz <= 0:
            return
        ti = int(t_s * self.rate_hz)
        if ti == self._tick_i:
            return
        self._tick_i = ti
        pose = self.pose_feed.pose()
        if pose is None:
            return
        r = self.rng(NS, self.unit, ti)    # seeded per tick - deterministic
        for e in self.truth_entities():
            lat, lng, ealt = e.pos_at(t_s, self.world)
            d = gp.geo_distance_m(pose["lat"], pose["lng"], lat, lng)
            if d > self.range_m:
                continue
            if r.random() < self.p_drop:
                continue
            # the reported position: truth + a seeded gaussian offset -
            # sensor_error measures this back out against truth.jsonl
            est_lat, est_lng = gp.geo_offset_to_latlng(
                lat, lng, r.gauss(0.0, self.noise_m),
                r.gauss(0.0, self.noise_m))
            self._seen += 1
            self.event({"tid": e.id, "range_m": round(d, 1),
                        "pos": [round(est_lat, 7), round(est_lng, 7),
                                round(ealt, 1)]})
            self.truth.append({"src": NS, "tid": e.id, "cls": e.cls,
                               "lat": est_lat, "lng": est_lng,
                               "range_m": round(d, 1), "sent": True},
                              ms=self.clock_ms())
        self.state({"seen": self._seen})


def main(argv):
    s = StubSensor(argv)
    if s.selftest:
        s.run_selftest()
        return 0
    s.connect(adverts=[__import__("json").dumps(ADVERT)])
    s.state({"seen": 0}, full=True)
    s.run()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
