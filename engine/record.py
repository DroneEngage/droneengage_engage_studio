#!/usr/bin/env python3
"""record.py - capture a human webclient session into a de.scenario/1
file (TASK-25 / SL-0028).

The capture seam is the comm server's `command_plugin` hook (the
TASK-24 decision): a generated plugin is written into the sim's server
dir and added to var/run/<sim>/server/de_server.config's
`command_plugin` list; de_server hands it every inbound parsed message
pre-routing. While armed, the plugin appends one JSONL row per frame to
var/run/<sim>/session.jsonl. finalize() maps the GCS-sourced rows onto
registry verbs (`./sim verbs`) and writes the scenario, its package /
deploy-spec sidecars and a <name>.md runbook stub. Frames with no verb
land in the timeline as `# unmapped:` comments - nothing is dropped
silently.

  ./sim record <sim.yaml|live-sim> -o scenarios/<name>.yaml
  ./sim run|view <file.yaml> --record <out.yaml>

On a real-server sim record patches `command_plugin` and restarts
de_server once (units and the GCS bridge re-dial). `fake` has no plugin
seam (refused). `external` is the user's own server stack: the plugin
file is still written and its path printed - it must be added to that
stack's server.config `command_plugin` list by hand for frames to land.
"""

import json
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import simlib
import ctl


# ------------------------------------------------------------- capture

# The generated plugin: one JSONL row per inbound parsed message while
# the armed marker exists. sd falls back to the socket's login senderID
# (the real server routes the client's sd; it is absent on the frame
# itself for sessions that never set it). processCommand MUST call cb -
# it runs pre-routing, a swallowed callback eats the command.
PLUGIN_JS = """// generated by `./sim record` - engine/record.py. While the armed
// marker exists, appends one JSONL row per inbound parsed message,
// stamped at the server BEFORE routing (the TASK-24 seam).
const fs = require('fs');
const OUT = %s;
const ARMED = %s;
module.exports.processCommand = function (p_ws, p_message, v_jmsg, nullIndex, cb) {
    try {
        if (v_jmsg && typeof v_jmsg === 'object' && v_jmsg.mt !== undefined
            && fs.existsSync(ARMED)) {
            const lr = (p_ws && p_ws.m_loginRequest) || {};
            fs.appendFileSync(OUT, JSON.stringify({
                t_ms: Date.now(),
                sd: v_jmsg.sd || lr.m_senderID || null,
                ty: v_jmsg.ty,
                tg: v_jmsg.tg || null,
                mt: v_jmsg.mt,
                ms: v_jmsg.ms === undefined ? null : v_jmsg.ms,
            }) + '\\n');
        }
    } catch (e) { /* capture must never break routing */ }
    if (typeof cb === 'function') cb(null, null);
};
"""


def session_path(name):
    return os.path.join(simlib.run_dir(name), "session.jsonl")


def plugin_path(name):
    return os.path.join(simlib.server_dir(name), "record_plugin.js")


def _armed_path(name):
    return os.path.join(simlib.run_dir(name), "record.armed")


def _write_plugin(name):
    simlib.write_text(plugin_path(name), PLUGIN_JS % (
        json.dumps(session_path(name)), json.dumps(_armed_path(name))))


def arm(m):
    """Enable capture on the sim's real server: write the plugin, put it
    in the generated de_server.config's command_plugin list and restart
    de_server so it loads (units + bridge re-dial). Then arm the marker
    and return the capture's t0 (unix ms)."""
    name = m["name"]
    srv = m["server"]
    if srv["type"] == "fake":
        raise simlib.SimError(
            "record needs the real comm server (the command_plugin "
            "seam) - this sim's server is fake")
    _write_plugin(name)
    if srv["type"] == "external":
        # the sim owns no server process - the plugin path goes into the
        # user's own server.config command_plugin list by hand
        print(simlib.col_yellow(
            f"server is external - add to its server.config "
            f"command_plugin and restart it:\n"
            f"  \"command_plugin\": [\"{plugin_path(name)}\"]"))
    else:
        cfg = os.path.join(simlib.server_dir(name), "de_server.config")
        scfg = json.load(open(cfg))
        plug = plugin_path(name)
        if plug not in (scfg.get("command_plugin") or []):
            scfg.setdefault("command_plugin", []).append(plug)
            simlib.write_json(cfg, scfg, indent=1)
            alive = {k.split(".", 1)[1] for k in
                     simlib.read_pids(name) if k.startswith("server.")}
            if "de_server" in alive:
                # a config change only lands on process start - bounce
                # de_server, then wait the fleet back online
                ctl.CTX = name
                ctl.kill_proc("server", "de_server")
                time.sleep(1)
                ctl.start_proc("server", "de_server")
                import launcher
                if not launcher.wait_port(srv["port"], 30):
                    raise simlib.SimError(
                        "de_server did not re-open its port - see "
                        f"{simlib.server_dir(name)}/logs/de_server.log")
                ctl.main(["wait_online", "120"])
    simlib.write_text(_armed_path(name), "1")
    simlib.write_text(session_path(name), "")
    return int(time.time() * 1000)


def disarm(m):
    try:
        os.unlink(_armed_path(m["name"]))
    except OSError:
        pass


def park(m):
    """Hold the record session open until Ctrl-C - the interactive
    window the human drives the webclient in."""
    print(simlib.col_bold("\n== recording - drive the webclient, "
                          "Ctrl-C to write the scenario =="), flush=True)
    print("webclient: " + simlib.col_cyan(simlib.webclient_url(m)),
          flush=True)
    print("planning:  " + simlib.col_cyan(
        simlib.webclient_url(m, "/planning", "GCSPLN_" + m["name"])),
        flush=True)
    print(simlib.col_dim("session: " + session_path(m["name"])),
          flush=True)
    try:
        while True:
            time.sleep(0.5)
    except KeyboardInterrupt:
        print("record released\n", flush=True)


# -------------------------------------------------------------- mapping

# mt=1010 F-codes (ANDRUAV_UNIT_MODE*) with a `mode` name a pymavlink
# mode-table lookup resolves; F 12 (NAV_LAND) and 22 (NAV_TAKEOFF) map
# to their own verbs below.
_F_MODE = {2: "RTL", 5: "AUTO", 6: "STABILIZE", 7: "ALT_HOLD",
           8: "MANUAL", 9: "GUIDED", 10: "LOITER", 11: "POSHOLD",
           13: "CIRCLE", 14: "FBWA", 15: "CRUISE", 16: "FBWB",
           17: "BRAKE", 21: "SMART_RTL", 23: "QHOVER", 24: "QLOITER",
           25: "QSTABILIZE", 26: "QLAND", 27: "QRTL", 28: "ACRO"}

# frames a GCS sends that read or poll but never act - dropped (the
# task's bar is only that ACTIONS are never dropped silently)
_NOISE = {1004, 9005, 9015, 1072, 1073, 6502}
_REMOTE_READ = {500, 501, 505, 507, 508}   # 1005 C codes: reads/queries
# 1005 C codes are RemoteExecute commands (100-599); C >= 600 is the
# pull convention - "send me message type C" (a live capture showed
# C:1004/1022/1029/1071 answered by mt 1022/1071 replies). Polling,
# not an operator action.
_PULL_C = 600

# actionable frames replayed verbatim as `send` steps - a GCS command
# the de.scenario/1 verb set has no semantic name for
_SENDABLE = {1005, 1027, 1028, 1033, 1034, 1035, 1040, 1046,
             1090, 6518}


def _gcs_rows(m, t0):
    """session.jsonl rows from GCS sessions after t0 - units, the bridge
    (gcs_party) and the scenario operator bot are not the human."""
    mine = {u["party_id"] for u in m["units"]}
    mine.add(m["server"].get("gcs_party") or simlib.GCS_PARTY)
    mine.add("GCS_OPERATOR")
    rows = []
    try:
        fh = open(session_path(m["name"]), errors="replace")
    except OSError:
        return rows
    for ln in fh:
        try:
            r = json.loads(ln)
        except ValueError:
            continue
        if not isinstance(r.get("t_ms"), int) or r["t_ms"] < t0:
            continue
        if r.get("ty") not in ("i", "g") or r.get("sd") in mine:
            continue
        rows.append(r)
    fh.close()
    return rows


def _unit_of(m, tg):
    """tg party -> unit name; _AGN_/_GD_/None -> 'all' (omit)."""
    if not tg or tg in ("_AGN_", "_GD_", "_GCS_"):
        return None
    for u in m["units"]:
        if u["party_id"] == tg:
            return u["name"]
    return tg


def _step_for(m, r):
    """(step_dict | 'noise' | None for unmapped) for one GCS row."""
    mt, ty, ms = r.get("mt"), r.get("ty"), r.get("ms")
    tg = r.get("tg")
    unit = _unit_of(m, tg)
    if mt in _NOISE:
        return "noise"
    ms = ms if isinstance(ms, dict) else {}
    if mt == 1030:                       # Arm {A: true} / disarm
        return {"do": "arm" if ms.get("A") else "disarm",
                **({"unit": unit} if unit else {})}
    if mt == 1031:                       # ChangeAltitude {a: alt_m} -
        # the takeoff/climb command; NAV_TAKEOFF to the same alt is the
        # closest replay verb
        st = {"do": "takeoff"}
        if ms.get("a") is not None:
            st["alt"] = ms["a"]
        if unit:
            st["unit"] = unit
        return st
    if mt == 1032:                       # NAV_LAND
        return {"do": "land", **({"unit": unit} if unit else {})}
    if mt == 1010:                       # FlightControl {F: code}
        f = ms.get("F")
        if f == 22:
            return {"do": "takeoff", **({"unit": unit} if unit else {})}
        if f == 12:
            return {"do": "land", **({"unit": unit} if unit else {})}
        if f in _F_MODE:
            return {"do": "mode", "mode": _F_MODE[f],
                    **({"unit": unit} if unit else {})}
        return None
    if mt == 1086:                       # DE supervisor action {a: ...}
        a = ms.get("a")
        if a == "start":                 # plain mission-control start
            st = {"do": "start"}
            if ms.get("mission"):
                st["mission"] = ms["mission"]
            return st
        if a in ("stop", "pause", "resume", "clear"):
            if a == "pause" and ms.get("hold") is not None:
                # `pause` has no hold arg - the operator form carries it
                st = {"do": "operator", "act": "pause",
                      "hold": bool(ms["hold"])}
            else:
                st = {"do": a}
            if ms.get("mission"):
                st["mission"] = ms["mission"]
            return st
        if a == "activate":
            st = {"do": "operator", "act": "activate",
                  "mission": ms.get("mission")}
            if unit:
                st["unit"] = unit
            return st
        if a == "fire":
            st = {"do": "fire", "event": ms.get("event")}
            if unit:
                st["unit"] = unit
            if ms.get("payload") is not None:
                st["payload"] = ms["payload"]
            return st
        if a in ("status", "journal"):
            return "noise"
        return None
    if mt == 1094:                       # DE operation control
        a = ms.get("a")
        if a == "prepare":
            return "prepare"             # grouped by the caller
        if a == "start":
            st = {"do": "start"}
            # run/t_start are session-bound: replay resolves the live
            # run id itself, and a captured absolute t_start is stale -
            # keep only the relative lead and the {role: mission} map
            for k in ("in_ms", "lead_ms", "start"):
                if ms.get(k) is not None:
                    st[k] = ms[k]
            return st
        if a == "abort":
            st = {"do": "abort"}
            if ms.get("why"):
                st["why"] = str(ms["why"])
            return st
        if a in ("status", "ready", "fail", "started", "aborted"):
            return "noise"
        return None
    if mt == 1085:                       # DE package upload - grouped
        return "pkg"
    if mt == 1061:                       # Sync event fire {d: name}
        if ms.get("d"):
            return {"do": "event", "event": ms["d"]}
        return None
    if mt == 1089:                       # unit capabilities
        if ms.get("r"):
            return "noise"
        return None
    if mt == 1005 and (ms.get("C") in _REMOTE_READ
                       or (isinstance(ms.get("C"), (int, float))
                           and ms["C"] >= _PULL_C)):
        return "noise"
    if mt in _SENDABLE:
        # verbatim replay through the ctl send path; big inline blobs
        # (a compiled package text) become {PKG:} sidecar tokens
        out = dict(ms)
        return {"do": "send", "ty": ty or "i", "mt": mt,
                "tg": tg or "_AGN_", "ms": out}
    return None


def _group_deploys(rows):
    """Pull the multi-frame actions out of the row stream: one 1094
    `prepare` deploy is one PREPARE per bound unit sharing a run id; one
    1085 upload is the same package hash to N units. Returns
    (deploys, rows_without_them); each deploy is
    {t_ms, kind: 'op'|'pkg', op, run, oh, roles|hash, units, pkg}."""
    deploys, rest = {}, []
    for r in rows:
        mt, ms = r.get("mt"), r.get("ms") or {}
        tag = None
        if mt == 1094 and isinstance(ms, dict) and ms.get("a") == "prepare":
            tag = ("op", ms.get("run") or ms.get("oh") or "")
        elif mt == 1085:
            tag = ("pkg", ms.get("hash") or "")
        if tag is None:
            rest.append(r)
            continue
        d = deploys.setdefault(tag, {"t_ms": r["t_ms"], "kind": tag[0],
                                     "op": "", "run": "", "oh": "",
                                     "hash": "", "roles": {},
                                     "units": [], "pkg": ""})
        d["t_ms"] = min(d["t_ms"], r["t_ms"])
        if tag[0] == "op":
            d["op"], d["run"] = ms.get("op", ""), ms.get("run", "")
            d["oh"] = ms.get("oh", "")
            # every PREPARE carries the same full bind map; the frame's
            # tg says which unit this copy is for and binds it to a role
            role = (ms.get("bind") or {}).get(r.get("tg"), "")
            us = d["roles"].setdefault(
                role, {"pkg": ms.get("pkg"), "units": []})
            us["pkg"] = us.get("pkg") or ms.get("pkg")
            if r.get("tg") not in us["units"]:
                us["units"].append(r["tg"])
        else:
            d["hash"] = ms.get("hash", "")
            d["pkg"] = ms.get("pkg") or d["pkg"]
            if r.get("tg") not in d["units"]:
                d["units"].append(r["tg"])
    return sorted(deploys.values(), key=lambda d: d["t_ms"]), rest


# ------------------------------------------------------------- writing

_FLOW_SAFE = re.compile(r"^[A-Za-z0-9_./{}:+-]+$")


def _scalar(v):
    """A yaml scalar/flow fragment for one step value."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (dict, list)):
        return json.dumps(v)
    s = str(v)
    if s and _FLOW_SAFE.match(s) and not s.startswith("{") \
            and s.lower() not in ("true", "false", "null", "yes", "no"):
        return s
    return json.dumps(s)


def _flow(d):
    return "{" + ", ".join(f"{k}: {_scalar(v)}" for k, v in d.items()
                           if v is not None) + "}"


def finalize(m, t0, out_path, name=None):
    """Turn the armed capture into the scenario + sidecars. Returns the
    (steps, unmapped, noise) counts for the caller's report."""
    out_path = os.path.abspath(out_path)
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    name = name or re.sub(r"\W+", "_",
                          os.path.splitext(os.path.basename(out_path))[0])
    rows = _gcs_rows(m, t0)
    deploys, rows = _group_deploys(rows)

    # sidecar package files + the deploy spec for a 1094 op deploy
    base_dir = os.path.dirname(out_path)
    stem = os.path.splitext(os.path.basename(out_path))[0]
    operation = None
    events = []            # (t_ms, step_dict) for deploys to merge in
    for i, d in enumerate(deploys):
        suffix = "" if len(deploys) == 1 else f"_{i + 1}"
        if d["kind"] == "op":
            spec = {"op": d["op"] or stem, "roles": {}}
            if d["oh"]:
                spec["oh"] = d["oh"]
            for role, r in d["roles"].items():
                pf = f"{stem}{suffix}.{role}.pkg.json"
                if r.get("pkg"):
                    simlib.write_text(os.path.join(base_dir, pf), r["pkg"])
                spec["roles"][role] = {
                    "pkg": pf,
                    "units": [_unit_of(m, u) or u
                              for u in r["units"]]}
            sf = f"{stem}{suffix}.deploy.json"
            simlib.write_json(os.path.join(base_dir, sf), spec, indent=1)
            events.append((round((d["t_ms"] - t0) / 1000.0, 1),
                           {"do": "deploy"}))
            operation = operation or sf
        else:
            pf = f"{stem}{suffix}.pkg.json"
            if d["pkg"]:
                simlib.write_text(os.path.join(base_dir, pf), d["pkg"])
            st = {"do": "deploy", "package": pf}
            us = [_unit_of(m, u) or u for u in d["units"]]
            if us and len(us) < len(m["units"]):
                st["unit"] = us[0] if len(us) == 1 else ",".join(us)
            events.append((round((d["t_ms"] - t0) / 1000.0, 1), st))
            operation = operation or pf

    steps, unmapped, n_noise = [], [], 0
    blobs = {}
    prev_unmapped = None     # collapse a held/repeated identical frame
    for r in rows:
        st = _step_for(m, r)
        if st in ("noise", "prepare", "pkg"):
            n_noise += (st == "noise")
            continue
        t = round((r["t_ms"] - t0) / 1000.0, 1)
        if st is None:
            key = (r.get("mt"), json.dumps(r.get("ms"), sort_keys=True))
            if prev_unmapped is not None and prev_unmapped[1] == key:
                prev_unmapped[0][2] += 1
                continue
            unmapped.append([t, r, 1])
            prev_unmapped = (unmapped[-1], key)
            continue
        prev_unmapped = None
        # park big inline blobs (package texts, mission exports) in
        # sidecars - a {PKG:} token keeps `send` replaying them verbatim
        for k, v in list((st.get("ms") or {}).items()):
            if isinstance(v, str) and len(v) > 4000:
                bf = f"{stem}.blob{len(blobs)}.json"
                blobs[bf] = v
                st["ms"][k] = "{PKG:%s}" % bf
        steps.append((t, st))
    for bf, text in blobs.items():
        simlib.write_text(os.path.join(base_dir, bf), text)

    timeline = sorted(steps + events, key=lambda e: e[0])
    # the tail silence after the last action is the human watching it
    # play out - keep it as a wait so the replay lasts as long
    tail = None
    if rows:
        end_t = timeline[-1][0] if timeline else 0.0
        gap = (max(r["t_ms"] for r in rows) - t0) / 1000.0 - end_t
        if gap >= 8:
            tail = {"t": end_t, "do": "wait", "seconds": round(gap)}

    utc = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(t0 / 1000))
    md = stem + ".md"
    lines = [
        f"# {name} - recorded webclient session on sim "
        f"'{m['name']}' at {utc} (./sim record). Replaying the file "
        "re-sends the operator's actions on the same clock offsets.",
        f"# Runbook: {md}",
        f"version: 1",
        f"name: {name}",
    ]
    sim_ref = _sim_ref(m)
    if sim_ref is not None:
        lines.append("sim: " + _flow(sim_ref))
    else:
        lines.append("# the recorded sim has no source file - the fleet"
                     " is inlined below")
        lines.append("transport: real")
        lines.append("fleet:")
        for u in m["units"]:
            ent = {"id": u["name"], "cls": u["block"]}
            lines.append("  - " + _flow(ent))
    if operation:
        lines.append(f"operation: {operation}")
    lines.append("timeline:")
    ti = 0
    def _comment(t, r, n):
        return "  # unmapped: %d %s%s" % (
            r["mt"], json.dumps(r.get("ms"), separators=(",", ":")),
            f" (x{n})" if n > 1 else "")

    for t, st in timeline:
        while ti < len(unmapped) and unmapped[ti][0] <= t:
            lines.append(_comment(*unmapped[ti]))
            ti += 1
        lines.append("  - " + _flow(dict(t=t, **st)))
    for t, r, n in unmapped[ti:]:
        lines.append(_comment(t, r, n))
    if tail:
        lines.append("  - " + _flow(tail))
    if not timeline and not unmapped:
        lines.append("  # (no operator actions were captured)")
    lines += [
        "# TODO asserts: what proves the replay did what the session",
        "# did? e.g. journal_count on 'mission main completed',",
        "# fleet_state, or a notification saw - see ./sim verbs",
        "assert: []",
        "teardown: land",
        "",
    ]
    simlib.write_text(out_path, "\n".join(lines))
    _write_runbook(m, name, out_path, md, operation)
    return len(timeline), len(unmapped), n_noise


def _sim_ref(m):
    """sim: block for the recorded file - the source yaml by sims-name
    when the manifest knows it, plus the CLI overlays (--with) that were
    applied when it was brought up."""
    sim_file = m.get("sim_file") or ""
    with_ = [x for x in (os.environ.get("SIM_WITH") or "").split(",")
             if x.strip()]
    if sim_file and os.path.isfile(sim_file):
        b = os.path.basename(sim_file)
        if os.path.dirname(os.path.abspath(sim_file)) == \
                os.path.join(simlib.SIM_ROOT, "sims") \
                and b.endswith((".yaml", ".yml")):
            ref = {"base": os.path.splitext(b)[0]}
        else:
            ref = {"base": sim_file}
        if with_:
            ref["with"] = with_
        return ref
    if sim_file:
        return {"base": sim_file}
    return None


def _write_runbook(m, name, out_path, md, operation):
    """The <name>.md stub the scenario convention pairs with the yaml."""
    p = os.path.join(os.path.dirname(out_path), md)
    lines = [
        f"# {name}",
        "",
        f"Recorded webclient session on sim `{m['name']}` "
        "(`./sim record`). The yaml replays the operator's actions at "
        "their original offsets; `# unmapped:` comments in the timeline "
        "are frames no verb exists for (they do not replay).",
        "",
        "## Run",
        "",
        "```sh",
        f"./sim validate {os.path.basename(out_path)}",
        f"./sim run {os.path.basename(out_path)}",
        "```",
        "",
    ]
    if operation:
        lines += [f"Deploys `{operation}` (captured package/spec "
                  "sidecar(s) beside this file).", ""]
    lines += [
        "## TODO",
        "",
        "- fill `assert:` with the check(s) that prove what the session "
        "was about",
        "- review `# unmapped:` frames - they need a verb (or a manual "
        "step) to replay",
        "",
    ]
    simlib.write_text(p, "\n".join(lines))


# ---------------------------------------------------------------- main

def _resolve(target):
    """record's target: a sim file (ensure it up), a live sim name, or a
    sims/<name>.yaml."""
    if os.path.isfile(target):
        import launcher
        return launcher.ensure(target, exclusive=False)
    m = simlib.load_manifest(target, required=False)
    if m:
        if not simlib.read_pids(target):
            raise simlib.SimError(
                f"sim {target!r} is down - `./sim up` it (or record the "
                "sim file) first")
        return m
    alt = os.path.join(simlib.SIM_ROOT, "sims",
                       target + ("" if target.endswith(".yaml")
                                 else ".yaml"))
    if os.path.isfile(alt):
        import launcher
        return launcher.ensure(alt, exclusive=False)
    raise simlib.SimError(
        f"{target!r}: not a file and no live sim or sims/{target}.yaml")


def main(argv):
    out, target, i = None, None, 0
    while i < len(argv):
        a = argv[i]
        if a == "-o":
            if i + 1 >= len(argv):
                sys.exit("record -o needs a path")
            out = argv[i + 1]
            i += 2
        elif not a.startswith("-") and target is None:
            target = a
            i += 1
        else:
            sys.exit(f"record: unknown argument {a!r}")
    if target is None or out is None:
        sys.exit("usage: ./sim record <sim.yaml|live-sim> "
                 "-o scenarios/<name>.yaml")
    m = _resolve(target)
    ctl.CTX = m["name"]
    t0 = arm(m)
    try:
        park(m)
    finally:
        disarm(m)
    n_steps, n_unmapped, n_noise = finalize(m, t0, out)
    print(f"wrote {out}: {n_steps} step(s)"
          + (f", {n_unmapped} unmapped frame(s) as comments"
             if n_unmapped else "")
          + f" ({n_noise} routine frames skipped)", flush=True)
    print(f"next: ./sim validate {out} && ./sim run {out}", flush=True)


